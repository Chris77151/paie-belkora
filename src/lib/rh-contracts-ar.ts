/** Projet (label / lieu / juridiction / site de production / ville d'arrêté) — même résolution que la version FR. */
function proj(v: RhContractView) {
  const preset = v.projectKey ? CONTRACT_PROJECTS[v.projectKey] : undefined;
  return {
    label: v.projectLabel?.trim() || preset?.label || PH,
    location: v.location?.trim() || preset?.location || PH,
    jurisdiction: v.jurisdiction?.trim() || preset?.jurisdiction || PH,
    productionSite: preset?.productionSite,
    faitCity: preset?.faitCity,
  };
}

/** Plafond d'exonération du panier (2× taux horaire SMIG) — identique à la version FR. */
const PANIER_CAP_AR = 35.84;

/** Paragraphe « 5.2 تعويض عن الوجبة » adapté au montant (exonéré, ou fraction réintégrée) — miroir de `panierParagraph`. */
function panierParagraphAr(dailyBasket?: string): string {
  const amount = Number((dailyBasket ?? "27").trim().replace(",", ".")) || 27;
  const shown = amount.toFixed(2).replace(".", ",");
  const base = `5.2. تعويض عن الوجبة. علاوةً على الأجر الأساسي، يتقاضى الأجير تعويضاً عن الوجبة قدره ${shown} درهم عن كلّ يوم عمل فعلي، إذ لا يسمح له العمل بالورش بتناول وجبته في منزله. ولهذا التعويض طبيعةُ تعويض عن مصاريف مهنية؛ `;
  if (amount <= PANIER_CAP_AR) {
    return `${base}وهو يظلّ دون السقف القانوني للإعفاء (ضِعف التعريفة الساعية للحدّ الأدنى للأجر، أي 35,84 درهم في اليوم)، ومن ثَمّ فهو معفى بالكامل من الاشتراكات ومن الضريبة على الدخل. ولا يُستحقّ في حالة الغياب أو توفير المشغّل للوجبة.`;
  }
  const excess = (amount - PANIER_CAP_AR).toFixed(2).replace(".", ",");
  return `${base}وهو معفى من الاشتراكات ومن الضريبة على الدخل في حدود السقف القانوني (ضِعف التعريفة الساعية للحدّ الأدنى للأجر، أي 35,84 درهم في اليوم)، ويُدمَج الجزء الزائد، أي ${excess} درهم عن كلّ يوم، في الوعاء الخاضع للاشتراكات وللضريبة. ولا يُستحقّ في حالة الغياب أو توفير المشغّل للوجبة.`;
}

/** Début de phrase « 5.1 salaire de base » selon que le salaire journalier est renseigné (sinon SMIG). */
function wageAr(v: RhContractView): string {
  const dw = v.dailyWage?.trim();
  return dw
    ? `أجراً أساسياً قدره ${dw} درهم`
    : "أجراً أساسياً محسوباً على أساس الحدّ الأدنى القانوني للأجر، أي سبعة عشر درهماً واثنين وتسعين سنتيماً (17,92 درهم) عن الساعة";
}

/** Forme juridique en arabe (fusha) selon la forme FR ; repli sur la valeur brute. */
function araLegalForm(firm: Firm): string {
  const f = (firm.legal_form ?? "").toLowerCase();
  if (f.includes("au") || f.includes("associé unique") || f.includes("associe unique"))
    return "شركة ذات مسؤولية محدودة ذات الشريك الوحيد";
  if (f.includes("sarl")) return "شركة ذات مسؤولية محدودة";
  if (f.includes("sas")) return "شركة مساهمة مبسّطة";
  if (f.startsWith("sa") || f.includes("société anonyme")) return "شركة مساهمة";
  if (f.includes("snc")) return "شركة تضامن";
  if (f.includes("auto") || f.includes("micro")) return "مقاول ذاتي";
  if (f.includes("physique") || f.includes("personne")) return "شخص ذاتي";
  return firm.legal_form?.trim() || "";
}

/** Montant en dirhams groupé par milliers avec point (ex. 100.000) — usage marocain courant. */
function araCapital(n?: number): string {
  return n && n > 0 ? n.toLocaleString("de-DE") : PH;
}

/** Paragraphe d'identification de l'employeur, en arabe, assemblé des champs réellement renseignés. */
function employerParagraphAr(firm: Firm): string {
  const forme = araLegalForm(firm);
  const parts: string[] = [`${firm.regime === "SMAG" ? "مقاولة" : "شركة"} ${firm.name}`];
  if (forme) parts.push(forme);
  if (firm.share_capital && firm.share_capital > 0) parts.push(`رأسمالها ${araCapital(firm.share_capital)} درهم`);
  if (firm.rc?.trim()) parts.push(`مسجّلة بالسجل التجاري${firm.rc_city?.trim() ? ` بـ${firm.rc_city.trim()}` : ""} تحت رقم ${firm.rc.trim()}`);
  if (firm.if_fiscal?.trim()) parts.push(`رقم التعريف الجبائي ${firm.if_fiscal.trim()}`);
  if (firm.cnss_affiliation?.trim()) parts.push(`رقم التسجيل بالضمان الاجتماعي ${firm.cnss_affiliation.trim()}`);
  if (firm.ice?.trim()) parts.push(`المعرّف الموحّد للمقاولة ${firm.ice.trim()}`);
  if (firm.address?.trim()) parts.push(`ومقرها الاجتماعي بـ${firm.address.trim()}`);
  parts.push(`ممثَّلةً من طرف ${val(firm.signatory_name)} بصفته(ها) ${val(firm.signatory_role)}`);
  return `${parts.join("، ")}، ويُشار إليها فيما بعد بـ«المشغّل»، من جهة؛`;
}

/** Bloc « parties » en arabe (employeur + salarié). */
function partiesArBlocks(v: RhContractView): LegalBlock[] {
  const e = v.employee;
  return [
    { k: "p", t: "بين الموقّعَين أسفله :" },
    { k: "h", t: "المشغّل" },
    { k: "p", t: employerParagraphAr(v.firm) },
    { k: "h", t: "الأجير" },
    {
      k: "ul",
      items: [
        `السيد(ة) : ${fullName(e)}`,
        `المزداد(ة) بتاريخ : ${valDate(v.birthDate ?? e.birth_date)}  —  بـ : ${val(v.birthPlace)}`,
        `الحامل(ة) لبطاقة التعريف الوطنية رقم : ${val(v.cin ?? e.cin)}  —  الجنسية : ${val(v.nationality)}`,
        `القاطن(ة) بـ : ${val(v.address ?? e.address)}`,
        `رقم التسجيل بالضمان الاجتماعي : ${val(v.cnss ?? e.cnss_number)}`,
      ],
    },
    { k: "p", t: "ويُشار إليه(ها) فيما بعد بـ«الأجير»، من جهة أخرى." },
    // Le « il a été convenu » est porté par le préambule lorsque le salarié est déjà connu (dispense d'essai).
    ...(v.priorEmployee ? [] : [{ k: "center" as const, t: "تم الاتفاق على ما يلي :", strong: true }]),
  ];
}

