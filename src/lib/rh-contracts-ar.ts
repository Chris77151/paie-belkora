/** Ville du « Fait à » — même logique que la version FR. */
function faitCityAr(v: RhContractView): string {
  const p = proj(v);
  return (v.issueCity?.trim() || (p.location !== PH ? p.location.split("(")[0].trim() : v.firm.city) || PH).trim() || PH;
}

